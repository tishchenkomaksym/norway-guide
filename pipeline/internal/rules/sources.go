// отсутствия функции. Поэтому собираем только проверяемое: в какой коммуне
// находится место, куда звонить и где читать официальные правила.
package rules

// Activity — вид деятельности, для которого нужны правила.
type Activity string

const (
	Fishing Activity = "fishing"
	Hunting Activity = "hunting"
)

// NationalRule — правило, действующее по всей стране.
//
// Национальные требования стабильны и хорошо документированы: экзамен
// охотника, госпошлины, необходимость местной карты. Их можно показывать
// как справку, потому что они не зависят от конкретной точки.
type NationalRule struct {
	Activity  Activity `json:"activity"`
	Title     string   `json:"title"`
	Body      string   `json:"body"`
	SourceURL string   `json:"source_url"`
	// Кто отвечает за правило: к нему обращаться за разъяснением.
	Authority string `json:"authority"`
}

