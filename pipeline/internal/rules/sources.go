// RulesFor возвращает национальные правила по виду деятельности.
func RulesFor(a Activity) []NationalRule {
	var out []NationalRule
	for _, r := range NationalRules {
		if r.Activity == a {
			out = append(out, r)
		}
	}
	return out
}
