// Package regions делит Норвегию на регионы для скачивания.
//
// Зачем вообще делить. Фотографии и полные описания весят под сотню
// мегабайт: класть их в бандл — значит просить человека скачать сто
// мегабайт ради приложения, которым он, возможно, воспользуется в одной
// поездке по одному фьорду. Поэтому контент режется на куски, которые
// качаются по кнопке перед поездкой (§5 спеки, уровень 3).
//
// Почему границы заданы прямоугольниками, а не настоящими границами
// фюльке. Точные границы — это шейпфайлы Kartverket, отдельная зависимость
// и лишние мегабайты в пайплайне ради задачи «решить, в какой архив
// положить фотографию». Турист тоже мыслит не фюльке, а направлениями:
// «фьорды», «север за полярным кругом», «окрестности Осло».
//
// Важное следствие: регионы обязаны покрывать страну целиком и без дыр.
// Место, не попавшее ни в один регион, окажется без фотографии навсегда,
// и никакой ошибки при сборке не возникнет. Поэтому последним идёт
// регион-уловитель, а тест проверяет, что в него попадают единицы.
package regions

import "fmt"

// Region — область скачивания.
type Region struct {
	ID     string
	NameNo string
	NameEn string
	// Границы: место относится к региону, если попадает в прямоугольник.
	// Порядок проверки важен — первый подошедший выигрывает.
	MinLat, MaxLat float64
	MinLon, MaxLon float64
}

// All — регионы в порядке проверки.
//
// Порядок не алфавитный и не случайный: сначала узкие области, потом
// широкие. Свальбард стоит первым, потому что он далеко и однозначен;
// «остальная Норвегия» — последней, она ловит всё, что не подошло.
var All = []Region{
	{
		ID: "svalbard", NameNo: "Svalbard", NameEn: "Svalbard",
		MinLat: 74.0, MaxLat: 81.5, MinLon: 5.0, MaxLon: 40.0,
	},
	{
		// Тромсё, Нордкапп, Финнмарк — всё, что за Полярным кругом
		// севернее Лофотен. Сюда едут за сиянием и китами.
		ID: "north", NameNo: "Nord-Norge", NameEn: "Northern Norway",
		MinLat: 68.6, MaxLat: 72.0, MinLon: 10.0, MaxLon: 32.0,
	},
	{
		// Лофотены, Вестеролен, Будё. Отдельно от остального севера:
		// это самостоятельная цель поездки, а не «по дороге в Тромсё».
		ID: "lofoten", NameNo: "Lofoten og Nordland", NameEn: "Lofoten and Nordland",
		MinLat: 65.0, MaxLat: 68.6, MinLon: 10.0, MaxLon: 20.0,
	},
	{
		// Тронхейм и вокруг.
		ID: "trondelag", NameNo: "Trøndelag", NameEn: "Trøndelag",
		MinLat: 62.5, MaxLat: 65.0, MinLon: 7.0, MaxLon: 15.0,
	},
	{
		// Ставангер, Прекестулен, Кьераг, Люсе-фьорд.
		//
		// Стоит перед фьордами намеренно: прямоугольники перекрываются,
		// и без этого Кьераг уезжал во «Фьорд-Норвегию». Он стоит на
		// Люсе-фьорде, в получасе от Прекестулена, и качать их порознь
		// бессмысленно — человек едет на оба за одну поездку.
		ID: "rogaland", NameNo: "Rogaland", NameEn: "Rogaland",
		MinLat: 58.2, MaxLat: 59.6, MinLon: 5.0, MaxLon: 7.2,
	},
	{
		// Фьорды: Берген, Гейрангер, Согне-фьорд, Олесунн, Хардангер.
		// Самый посещаемый регион страны и самый тяжёлый по фотографиям.
		ID: "fjords", NameNo: "Fjord-Norge", NameEn: "Fjord Norway",
		MinLat: 59.0, MaxLat: 63.2, MinLon: 4.0, MaxLon: 8.6,
	},
	{
		// Кристиансанн и южное побережье.
		ID: "south", NameNo: "Sørlandet", NameEn: "Southern Norway",
		MinLat: 57.5, MaxLat: 59.3, MinLon: 6.5, MaxLon: 10.0,
	},
	{
		// Осло, Лиллехаммер, Йотунхеймен, Тролльстиген — всё восточное.
		ID: "east", NameNo: "Østlandet", NameEn: "Eastern Norway",
		MinLat: 58.5, MaxLat: 62.8, MinLon: 7.5, MaxLon: 13.0,
	},
	{
		// Уловитель. Без него место, не попавшее ни в один прямоугольник,
		// осталось бы без фотографий навсегда и молча.
		ID: "other", NameNo: "Resten av Norge", NameEn: "Rest of Norway",
		MinLat: -90, MaxLat: 90, MinLon: -180, MaxLon: 180,
	},
}

// For возвращает регион точки. Всегда возвращает регион: последний в
// списке ловит всё.
func For(lat, lon float64) Region {
	for _, r := range All {
		if lat >= r.MinLat && lat <= r.MaxLat &&
			lon >= r.MinLon && lon <= r.MaxLon {
			return r
		}
	}
	return All[len(All)-1]
}

// ByID ищет регион по идентификатору.
func ByID(id string) (Region, error) {
	for _, r := range All {
		if r.ID == id {
			return r, nil
		}
	}
	return Region{}, fmt.Errorf("регион %q не найден", id)
}
