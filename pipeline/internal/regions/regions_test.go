package regions

import "testing"

// Известные места: проверка, что прямоугольники не разъехались с картой.
//
// Тест написан по местам из топа, а не по случайным координатам: если
// Прекестулен окажется в «остальной Норвегии», это заметит любой, кто
// откроет приложение, и лучше узнать об этом здесь.
func TestFor(t *testing.T) {
	cases := []struct {
		name     string
		lat, lon float64
		want     string
	}{
		{"Прекестулен", 58.9864, 6.1904, "rogaland"},
		{"Кьераг", 59.0342, 6.5931, "rogaland"},
		{"Гейрангер-фьорд", 62.1008, 7.0947, "fjords"},
		{"Брюгген, Берген", 60.3975, 5.3242, "fjords"},
		{"Тролльтунга", 60.1242, 6.7400, "fjords"},
		{"Нерёй-фьорд", 60.9167, 6.9333, "fjords"},
		{"Вёрингсфоссен", 60.4267, 7.2506, "fjords"},
		{"Оперный театр, Осло", 59.9075, 10.7528, "east"},
		{"Парк Вигеланна", 59.9269, 10.6997, "east"},
		{"Холменколлен", 59.9639, 10.6667, "east"},
		// Тролльстиген стоит в Ромсдале — это фьордовая Норвегия,
		// а не восточная. Первая версия теста ошибалась, код был прав.
		{"Тролльстиген", 62.4575, 7.6708, "fjords"},
		{"Бессегген", 61.5042, 8.7320, "east"},
		{"Нидаросский собор", 63.4269, 10.3969, "trondelag"},
		{"Рейне", 67.9322, 13.0894, "lofoten"},
		{"Лофотены", 68.3333, 14.6667, "lofoten"},
		{"Нордкапп", 71.1725, 25.7844, "north"},
		{"Лонгйир", 78.2232, 15.6469, "svalbard"},
		{"Кристиансанн", 58.1467, 7.9956, "south"},
	}

	for _, c := range cases {
		got := For(c.lat, c.lon)
		if got.ID != c.want {
			t.Errorf("%s (%.4f, %.4f): регион %q, ожидался %q",
				c.name, c.lat, c.lon, got.ID, c.want)
		}
	}
}

// Уловитель обязан существовать и стоять последним: без него место,
// не попавшее ни в один прямоугольник, осталось бы без фотографий молча.
func TestCatchAllIsLast(t *testing.T) {
	last := All[len(All)-1]
	if last.ID != "other" {
		t.Fatalf("последним должен идти уловитель, а идёт %q", last.ID)
	}
	if r := For(0, 0); r.ID != "other" {
		t.Errorf("точка вне Норвегии попала в %q, ожидался уловитель", r.ID)
	}
}

func TestByID(t *testing.T) {
	if _, err := ByID("fjords"); err != nil {
		t.Errorf("fjords не найден: %v", err)
	}
	if _, err := ByID("несуществующий"); err == nil {
		t.Error("для несуществующего региона ожидалась ошибка")
	}
}
